import assert from "node:assert/strict";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(path.join(process.env.TZA_UI_DEPS || "/tmp/tza-ui-deps", "package.json"));
const { JSDOM } = require("jsdom"), { build } = require("esbuild");
const root = fileURLToPath(new URL("../", import.meta.url));
const bundle = await build({ entryPoints: [path.join(root,"web/ui-select.js")], bundle: true, format: "iife", write: false });
const dom = new JSDOM('<select><option value="a">First</option><option value="b">Second</option><option value="c" disabled>Unavailable</option></select>', { runScripts:"outside-only", url:"http://127.0.0.1" });
const { window } = dom;
window.eval(bundle.outputFiles[0].text);
window.document.dispatchEvent(new window.Event("DOMContentLoaded"));
await new Promise(resolve=>setTimeout(resolve,0));
const select=window.document.querySelector("select"), trigger=window.document.querySelector(".select-trigger");
select.value="b"; select.dispatchEvent(new window.Event("change",{bubbles:true}));
assert.equal(trigger.textContent.trim(),"Second");
trigger.click();
const disabled=window.document.querySelector('[data-i="2"]');
assert.equal(disabled.getAttribute("aria-disabled"),"true");
disabled.click(); assert.equal(select.value,"b");
window.document.querySelector('[data-i="0"]').click(); assert.equal(select.value,"a");
dom.window.close();
console.log("PASS: native selection updates visible trigger; unavailable family cannot be selected.");
