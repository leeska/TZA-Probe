const { window } = dom;
window.AbortController = AbortController;
const style = window.document.createElement("style");
style.textContent = css.slice(css.indexOf("[data-node-plugin-detail] {"));
window.document.head.append(style);
window.fetch = async () => new Response(JSON.stringify({ nodes: [{ id: "node", name: "Example", policy: { revision: 1, enabled: true, country: "US", services: ["google", "meta"], expected_ip: "8.8.8.8" }, egress: { enabled: true, received_at: Date.now() / 1000, allowed_ips: ["8.8.8.8"] } }], jobs: [], environments: { US: { locale: "en-US", timezone: "America/New_York" } }, worker_seen: Date.now() / 1000 }));
