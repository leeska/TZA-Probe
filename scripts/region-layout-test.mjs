import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(path.join(process.env.TZA_UI_DEPS || "/tmp/tza-ui-deps", "package.json"));
const { JSDOM } = require("jsdom");
const { build } = require("esbuild");
const root = fileURLToPath(new URL("../", import.meta.url));
const bundle = await build({ stdin: { contents: 'export { renderIPGuard } from "./web/admin-ip-guard.js";', resolveDir: root }, bundle: true, format: "iife", globalName: "guardUI", write: false });
const css = await readFile(path.join(root, "web/styles.css"), "utf8");
