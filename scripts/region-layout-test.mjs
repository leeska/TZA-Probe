await window.guardUI.renderIPGuard(window.document.querySelector("main"));
const computed = selector => window.getComputedStyle(window.document.querySelector(selector));
assert.equal(computed("[data-node-plugin-detail]").paddingInline, "var(--space-6)");
assert.equal(computed(".region-page").width, "100%");
assert.equal(computed(".region-options .select-trigger").height, "42px");
