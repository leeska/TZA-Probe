// Render the real alert page with independent current-state and history data.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";
const require = createRequire(path.join(process.env.TZA_UI_DEPS || "/tmp/tza-ui-deps", "package.json"));
const { JSDOM } = require("jsdom");
const { build } = require("esbuild");
const root = fileURLToPath(new URL("../", import.meta.url));
const bundle = await build({ stdin: { contents: 'export { renderAlerts } from "./web/admin-alerts.js"; export { state } from "./web/admin-state.js";', resolveDir: root }, bundle: true, format: "iife", globalName: "Alerts", write: false });
const dom = new JSDOM('<main id="admin-content"></main><dialog id="dialog"></dialog><div id="toast"></div>', { url: "http://127.0.0.1/admin", runScripts: "outside-only" });
const w = dom.window;
w.matchMedia = () => ({ matches: false, addEventListener() {} });
const snapshot = { id: 7, node_id: "node", node_name: "<img src=x onerror=alert(1)>", kind: "cpu", active: true, at: Date.now() / 1000, message: "当前 CPU：99%\n指标采样：上一次有效上报", attempts: 0, delivered: true };
let current = [{ ...snapshot, evaluation_paused: true }];
const history = [snapshot];
w.fetch = async (url) => {
  let data;
  if (url.includes("/admin/events?active=1")) data = current;
  else if (url.includes("/admin/events?")) data = history;
  else if (url.endsWith("/admin/notification")) data = { channel: "none" };
  else if (url.endsWith("/admin/plugins")) data = [];
  else throw new Error("Unexpected request: " + url);
  return new Response(JSON.stringify(data), { headers: { "Content-Type": "application/json" } });
};
w.eval(bundle.outputFiles[0].text);
const { state, renderAlerts } = w.Alerts;
state.container = w.document;
await renderAlerts();
const panel = w.document.querySelector("#admin-content");
const status = () => panel.querySelector('#event-rows [data-label="状态"]').textContent;
assert.equal(status(), "待确认");
assert.match(panel.querySelector("[data-alert-paused]").textContent, /保留上次告警.*等待有效读数确认/);
assert(panel.querySelector(".event-message").textContent.includes(snapshot.message), "preserve and label the old event snapshot");
assert.equal(panel.querySelectorAll("img").length, 0, "escape node names");
state.alertView = "events";
await renderAlerts();
assert.equal(status(), "触发", "history stays at its event-time state");
assert.equal(panel.querySelector("[data-alert-paused]"), null);
state.alertView = "active";
current = [{ ...snapshot }];
await renderAlerts();
assert.equal(status(), "触发");
assert.equal(panel.querySelector("[data-alert-paused]"), null, "valid readings clear the live warning");
current = [];
await renderAlerts();
assert.match(panel.querySelector("#event-rows").textContent, /当前没有正在告警/);
dom.window.close();
console.log("PASS: paused alerts, preserved history, resumed evaluation, recovery and escaped event content.");
