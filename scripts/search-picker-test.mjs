import assert from "node:assert/strict";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(path.join(process.env.TZA_UI_DEPS || "/tmp/tza-ui-deps", "package.json"));
const { JSDOM } = require("jsdom");
const { build } = require("esbuild");
const root = fileURLToPath(new URL("../", import.meta.url));
const bundle = await build({ stdin: { contents: 'export * from "./web/environment-picker.js"; export * from "./web/search-picker.js";', resolveDir: root }, bundle: true, format: "iife", globalName: "pickerUI", write: false });
const dom = new JSDOM('<main></main><dialog id="dialog"></dialog><div id="toast"></div>', { url: "http://127.0.0.1/admin", runScripts: "outside-only" });
const { window } = dom;
window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
window.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new window.Event("close")); };
window.eval(bundle.outputFiles[0].text);
const ui = window.pickerUI;
const content = window.document.querySelector("main");
content.innerHTML = `<form>${ui.environmentPicker("检测时区", "timezone", "America/Chicago", "timezone")}${ui.environmentPicker("检测语言", "locale", "en-US", "language")}${ui.environmentPicker("目标地区", "country", "DE", "country")}${ui.searchPicker("本机方案", "profile", "old-approved-v1", [{ value: "current-v2", label: "当前方案" }], { allowCustom: false })}${ui.environmentPicker("实验语言", "experiment_locale", "en-DE", "language")}</form>`;
ui.wireSearchPickers(content);
ui.wireSearchPickers(content);
const field = name => content.querySelector(`[name="${name}"]`);
const box = name => field(name).closest("[data-search-picker]");
const pop = name => box(name).querySelector('.select-pop');
const visible = name => [...pop(name).querySelectorAll('[role="option"]')].filter(option => !option.hidden);
const input = (name, value) => { field(name).value = value; field(name).dispatchEvent(new window.Event("input", { bubbles: true })); };
const key = (name, value, extra = {}) => {
  const event = new window.KeyboardEvent("keydown", { key: value, bubbles: true, cancelable: true, ...extra });
  field(name).dispatchEvent(event);
  return event;
};
const selected = name => [...pop(name).querySelectorAll('[aria-selected="true"]')].map(option => option.dataset.choiceValue);
assert(ui.environmentChoices("timezone").some(choice => choice.value === "UTC"));
assert(ui.environmentChoices("timezone").length > 40);
assert(ui.environmentChoices("language").length > 80);
assert(ui.environmentChoices("country").some(choice => choice.value === "JP"));
const ids = [...content.querySelectorAll("[id]")].map(element => element.id);
assert.equal(ids.length, new Set(ids).size);
assert.equal(field("timezone").getAttribute("aria-controls"), pop("timezone").querySelector('[role="listbox"]').id);
assert.equal(field("locale").value, "en-US");
assert.equal(field("experiment_locale").value, "en-DE");
assert.equal(field("experiment_locale").checkValidity(), true, "current custom values are preserved");
field("timezone").focus();
assert.equal(pop("timezone").hidden, false);
assert(visible("timezone").length > 40, "focus opens the full catalog instead of filtering by the old value");
input("timezone", "新加坡");
assert.equal(visible("timezone")[0].dataset.choiceValue, "Asia/Singapore");
key("timezone", "ArrowDown");
assert.equal(field("timezone").getAttribute("aria-activedescendant"), visible("timezone")[0].id);
assert.equal(key("timezone", "Enter").defaultPrevented, true);
assert.equal(field("timezone").value, "Asia/Singapore");
assert.equal(pop("timezone").hidden, true);
assert.deepEqual(selected("timezone"), ["Asia/Singapore"]);
let changes = 0;
field("timezone").addEventListener("change", () => { changes++; });
input("timezone", "los angeles");
assert(visible("timezone").some(option => option.dataset.choiceValue === "America/Los_Angeles"));
visible("timezone").find(option => option.dataset.choiceValue === "America/Los_Angeles").click();
assert.equal(changes, 1, "repeated wiring does not duplicate callbacks");
assert.equal(field("timezone").value, "America/Los_Angeles");
input("locale", "日语");
assert(visible("locale").some(option => option.dataset.choiceValue === "ja-JP"));
input("locale", "japanese");
assert(visible("locale").some(option => option.dataset.choiceValue === "ja-JP"));
input("locale", "zh-tw");
assert.equal(visible("locale")[0].dataset.choiceValue, "zh-TW");
input("locale", "en-DE");
assert.equal(field("locale").checkValidity(), true, "custom locale codes remain editable");
assert.equal(pop("locale").querySelector(".combo-empty").hidden, false);
assert.equal(key("locale", "Enter").defaultPrevented, true, "enter closes a custom value without accidentally submitting");
assert.equal(field("locale").value, "en-DE");
input("country", "德国");
assert(visible("country").some(option => option.dataset.choiceValue === "DE"));
input("country", "germany");
assert(visible("country").some(option => option.dataset.choiceValue === "DE"));
input("country", "deguo");
assert(visible("country").some(option => option.dataset.choiceValue === "DE"));
input("country", "DE");
key("country", "ArrowUp");
assert.equal(field("country").getAttribute("aria-activedescendant"), visible("country").at(-1).id);
key("country", "Escape");
assert.equal(pop("country").hidden, true);
assert.equal(field("country").hasAttribute("aria-activedescendant"), false);
input("locale", "日");
const ime = key("locale", "Enter", { isComposing: true });
assert.equal(ime.defaultPrevented, false);
assert.equal(pop("locale").hidden, false, "IME confirmation does not select an unintended option");
key("locale", "Tab");
assert.equal(pop("locale").hidden, true);
field("profile").focus();
assert.equal(field("profile").checkValidity(), true, "previously approved profiles remain available");
input("profile", "unapproved-v3");
assert.equal(field("profile").checkValidity(), false);
input("profile", "current");
key("profile", "ArrowDown");
key("profile", "Enter");
assert.equal(field("profile").value, "current-v2");
assert.equal(field("profile").checkValidity(), true);
field("profile").blur();
assert.equal(pop("profile").hidden, true);
content.insertAdjacentHTML("beforeend", `<fieldset disabled>${ui.environmentPicker("禁用时区", "disabled_timezone", "UTC", "timezone")}</fieldset>`);
ui.wireSearchPickers(content);
box("disabled_timezone").querySelector("button").click();
assert.equal(pop("disabled_timezone").hidden, true);
const form = content.querySelector("form");
const formData = new window.FormData(form);
assert.equal(formData.get("timezone"), "America/Los_Angeles");
assert.equal(formData.get("locale"), "日");
assert.equal(formData.get("profile"), "current-v2");
const hostile = ui.searchPicker("安全字段", "safe", '<img src=x onerror="alert(1)">', [{ value: "safe", label: "<svg onload=alert(1)>" }]);
content.insertAdjacentHTML("beforeend", hostile);
assert.equal(content.querySelector("img,svg"), null);
content.insertAdjacentHTML("beforeend", ui.environmentPicker("启用地区", "enable_country", "", "country", { allowedValues: ui.enableCountries, allowCustom: false }));
ui.wireSearchPickers(content);
assert.equal(pop("enable_country").querySelectorAll('[role="option"]').length, ui.enableCountries.length);
assert.equal(pop("enable_country").querySelector('[data-choice-value="CN"]'), null, "enablement only offers countries supported by the server");
input("enable_country", "ZZ");
assert.equal(field("enable_country").checkValidity(), false);

dom.window.close();
const fallback = new JSDOM("<main></main>", { runScripts: "outside-only" });
fallback.window.eval("Intl.supportedValuesOf = undefined; Intl.DisplayNames = undefined;");
fallback.window.eval(bundle.outputFiles[0].text);
assert(fallback.window.pickerUI.environmentChoices("timezone").some(choice => choice.value === "UTC"));
assert(fallback.window.pickerUI.environmentChoices("language").some(choice => choice.value === "en-US"));
fallback.window.close();
console.log("PASS: searchable language/timezone/country catalogs, bilingual and pinyin search, keyboard/IME, manual values, approved profiles, disabled fields and escaping.");
