import assert from "node:assert/strict";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(path.join(process.env.TZA_UI_DEPS || "/tmp/tza-ui-deps", "package.json"));
const { JSDOM } = require("jsdom"), { build } = require("esbuild");
const root = fileURLToPath(new URL("../", import.meta.url));
const bundle = await build({ stdin: { contents: 'export * from "./web/node-location.js"; export * from "./web/location-picker.js";', resolveDir: root }, bundle: true, format: "iife", globalName: "guardUI", write: false });
const dom = new JSDOM('<main></main><div id="toast"></div>', { url: "http://127.0.0.1", runScripts: "outside-only" });
const { window } = dom;
window.AbortController = AbortController;
const now = Math.floor(Date.now() / 1000);
const position = { latitude: 35.68, longitude: 139.69, country: "JP", city: "Tokyo", timezone: "Asia/Tokyo" };
const environments = { JP: { locale: "ja-JP", timezone: "Asia/Tokyo" }, US: { locale: "en-US", timezone: "America/New_York" } };
let data = { nodes: [{ id: "first", name: "First", egress: { enabled: true, received_at: now, allowed_ips: ["8.8.8.8"] } }], jobs: [], tasks: [], node_settings: {}, pending: {}, worker_seen: now, worker_configured: true, environments };
const requests = [];
window.fetch = async (url, options = {}) => {
  requests.push({ url, method: options.method || "GET", body: options.body ? JSON.parse(options.body) : null });
  if (url.includes("/places?")) return new Response(JSON.stringify([{ name: "<img src=x> Tokyo", ...position }]));
  if (url.endsWith("/locate")) return new Response(JSON.stringify({ ip: "203.0.113.9", country_code: "JP", country: "日本", province: "东京都", city: "东京", region: "日本", supported: true, ...position, timezone: "Asia/Tokyo" }));
  if (url.includes("/ipguard/location")) return new Response(JSON.stringify(options.method ? position : { ip: "8.8.8.8", position }));
  if (url.includes("/node-settings/")) return options.method === "DELETE" ? new Response(null, { status: 204 }) : new Response(JSON.stringify({ settings: JSON.parse(options.body), pending: "" }));
  return new Response(JSON.stringify(data));
};
window.eval(bundle.outputFiles[0].text);
const ui = window.guardUI;
const tick = () => new Promise((resolve) => setTimeout(resolve, 20));
const mount = async () => {
  const main = window.document.querySelector("main");
  main.innerHTML = `<form><input name="region" value="">${ui.autoLocateHTML(true)}${ui.driftHTML()}</form>`;
  const form = main.querySelector("form");
  const control = ui.wireNodeLocation(form, { id: "first", name: "First" });
  await tick();
  return { form, control };
};
// 节点表单里的「所在地区与定位」：还没有设置时目标地区留空、提示加入任务。
let { form, control } = await mount();
const box = form.querySelector("[data-node-drift]");
assert.equal(form.querySelector('[name="drift_country"]').value, "");
assert.match(box.textContent, /还没有加入地区偏移检测任务/);
assert.equal(await control.save("first"), "", "没改动时不写");
assert.equal(requests.filter((r) => r.method !== "GET").length, 0);
// 自动检测：节点所在地区填中文名；目标地区还空着时一并填上目标地区与定位。
form.querySelector("[data-auto-locate]").click();
await tick();
assert.equal(form.elements.region.value, "日本");
assert.equal(form.querySelector('[name="drift_country"]').value, "JP");
assert.match(form.querySelector("[data-locate-status]").textContent, /203\.0\.113\.9/);
// 地点搜索：回车才搜，结果名转义；选中后查询定位。
const details = form.querySelector("details"), search = form.querySelector('[type="search"]');
details.open = true;
search.value = "Tokyo";
search.dispatchEvent(new window.Event("input", { bubbles: true }));
assert.equal(requests.filter((r) => r.url.includes("places")).length, 0, "typing does not search");
search.dispatchEvent(new window.KeyboardEvent("keydown", { key: "Enter", bubbles: true, cancelable: true }));
await tick();
assert.equal(form.querySelectorAll(".region-place-results button").length, 1);
assert.equal(form.querySelector(".region-place-results img"), null, "place names must be escaped");
form.querySelector(".region-place-results button").click();
await tick();
assert.equal(form.querySelector('[name="latitude"]').value, "35.68");
// 手填经纬度后必须先确认定位才能保存。
const latitude = form.querySelector('[name="latitude"]');
latitude.value = "40"; latitude.dispatchEvent(new window.Event("input", { bubbles: true }));
assert.match(control.check(), /确认定位/);
form.querySelector("[data-confirm-location]").click();
await tick();
assert.equal(control.check(), "");
assert.equal(await control.save("first"), "");
const put = requests.filter((r) => r.method === "PUT").at(-1);
assert.equal(put.url, "/api/v1/admin/ipguard/node-settings/first");
assert.deepEqual(put.body, { country: "JP", family: "ipv4", position });
control.dispose();
// 已有设置时回填；清空目标地区即删除设置。
data = { ...data, tasks: [{ id: "t", name: "日本节点", enabled: true, services: ["google"], node_ids: ["first"] }], node_settings: { first: { country: "JP", family: "ipv4", position } } };
({ form, control } = await mount());
assert.equal(form.querySelector('[name="drift_country"]').value, "JP");
assert.match(form.querySelector("[data-node-drift]").textContent, /所属地区偏移检测任务：日本节点/);
assert.equal(await control.save("first"), "", "回填后原样保存不写");
const country = form.querySelector('[name="drift_country"]');
country.value = ""; country.dispatchEvent(new window.Event("change", { bubbles: true }));
assert.equal(await control.save("first"), "已清除地区偏移设置");
assert.equal(requests.at(-1).method, "DELETE");
control.dispose();
const mapArea = window.document.createElement("section");
window.document.body.append(mapArea);
mapArea.innerHTML = window.guardUI.locationPicker(position);
const map = mapArea.querySelector("[data-map]"), mapDetails = mapArea.querySelector("details");
Object.defineProperties(map, { clientWidth: { value: 768 }, clientHeight: { value: 280 } });
const update = window.guardUI.wireLocationPicker(mapArea, position, () => {}, async () => []);
update(position);
assert.equal(mapArea.querySelectorAll("[data-map-tiles] img").length, 0, "collapsed map must not request tiles");
mapDetails.open = true;
mapDetails.dispatchEvent(new window.Event("toggle"));
const images = [...mapArea.querySelectorAll("[data-map-tiles] img")];
assert(images.length > 0);
assert(images.every(image => image.referrerPolicy === "origin"), "map must send its site origin despite page-level same-origin policy");
assert(images.every(image => /^https:\/\/tile\.openstreetmap\.org\/\d+\/\d+\/\d+\.png$/.test(image.src)), "stable tile URLs preserve native HTTP caching");
update(position);
assert.deepEqual([...mapArea.querySelectorAll("[data-map-tiles] img")], images, "unchanged viewport must reuse tile elements");
map.dispatchEvent(new window.KeyboardEvent("keydown", { key: "ArrowRight", bubbles: true, cancelable: true }));
const movedImages = [...mapArea.querySelectorAll("[data-map-tiles] img")];
assert(movedImages.some(image => images.includes(image)), "panning must reuse overlapping tiles");
map.dispatchEvent(new window.KeyboardEvent("keydown", { key: "Enter", bubbles: true, cancelable: true }));
assert(Math.abs(Number(mapArea.querySelector('[name="longitude"]').value) - (position.longitude + 64 / (256 * 2 ** 5) * 360)) < 0.00001, "moving and selecting must preserve the actual longitude instead of jumping 180 degrees");
mapDetails.open = false;
update({ ...position, latitude: 40 });
assert.deepEqual([...mapArea.querySelectorAll("[data-map-tiles] img")], movedImages, "closed map must not fetch a new viewport");
update.dispose();
dom.window.close();
