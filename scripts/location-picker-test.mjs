import assert from "node:assert/strict";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(path.join(process.env.TZA_UI_DEPS || "/tmp/tza-ui-deps", "package.json"));
const { JSDOM } = require("jsdom"), { build } = require("esbuild");
const root = fileURLToPath(new URL("../", import.meta.url));
const bundle = await build({ stdin: { contents: 'export * from "./web/admin-ip-guard.js"; export * from "./web/location-picker.js";', resolveDir: root }, bundle: true, format: "iife", globalName: "guardUI", write: false });
const dom = new JSDOM('<main></main><div id="toast"></div>', { url: "http://127.0.0.1", runScripts: "outside-only" });
const { window } = dom;
window.AbortController = AbortController;
const timers = [];
window.setTimeout = callback => { timers.push(callback); return timers.length; };
window.clearTimeout = () => {};
const now = Math.floor(Date.now()/1000);
const position = { latitude: 35.68, longitude: 139.69, country: "JP", city: "Tokyo", timezone: "Asia/Tokyo" };
const nodes = [{ id: "first", name: "First", egress: { enabled: true, received_at: now, allowed_ips: ["8.8.8.8"] } }];
const data = { nodes, jobs: [], worker_seen: now, environments: { JP: { locale: "ja-JP", timezone: "Asia/Tokyo" }, US: { locale: "en-US", timezone: "America/New_York" } } };
const requests = [];
window.fetch = async (url, options = {}) => {
  requests.push({ url, options });
  if (url.includes("/places?")) return new Response(JSON.stringify([{ name: '<img src=x> Tokyo', ...position }]));
  if (url.includes("/location")) return new Response(JSON.stringify(options.method ? position : { ip: "8.8.8.8", position }));
  return new Response(JSON.stringify(data));
};
window.eval(bundle.outputFiles[0].text);
const area = window.document.querySelector("main");
await window.guardUI.renderIPGuard(area);
await new Promise(resolve => setTimeout(resolve, 20));
assert.equal(area.querySelector('[name="country"]').value, "JP", "new policy defaults from measured exit IP");
assert.match(area.querySelector("[data-location-status]").textContent, /8.8.8.8/);
const details = area.querySelector("details"), search = area.querySelector('[type="search"]');
details.open = true;
search.value = "Tokyo";
search.dispatchEvent(new window.Event("input", { bubbles: true }));
assert.equal(requests.filter(request => request.url.includes("places")).length, 0, "typing does not search or save");
search.dispatchEvent(new window.KeyboardEvent("keydown", { key: "Enter", bubbles: true, cancelable: true }));
await new Promise(resolve => setTimeout(resolve, 20));
assert.equal(area.querySelectorAll(".region-place-results button").length, 1);
assert.equal(area.querySelector(".region-place-results img"), null, "place names must be escaped");
await timers.find(callback => callback.name === "poll")();
assert.equal(area.querySelector('[type="search"]'), search);
assert.equal(search.value, "Tokyo"); assert(details.open);
area.querySelector(".region-place-results button").click();
await new Promise(resolve => setTimeout(resolve, 20));
assert.equal(area.querySelector('[name="latitude"]').value, "35.68");
assert.equal(requests.filter(request => request.options.method === "POST").length, 1);
const latitude = area.querySelector('[name="latitude"]');
latitude.value = "40"; latitude.dispatchEvent(new window.Event("input", { bubbles: true }));
assert(area.querySelector('[type="submit"]').disabled, "coordinates require confirmation before saving");
area.querySelector("[data-confirm-location]").click();
await new Promise(resolve => setTimeout(resolve, 20));
assert(!area.querySelector('[type="submit"]').disabled);
area.disposeRegionGuard();
const mapArea = window.document.createElement("section");
window.document.body.append(mapArea);
mapArea.innerHTML = window.guardUI.locationPicker(position);
const map = mapArea.querySelector("[data-map]"), mapDetails = mapArea.querySelector("details");
Object.defineProperties(map, { clientWidth: { value: 768 }, clientHeight: { value: 280 } });
const update = window.guardUI.wireLocationPicker(mapArea, position, () => {}, async () => []);
update(position);
assert.equal(mapArea.querySelectorAll("[data-map-tiles] img").length, 0, "collapsed map must not request tiles");
mapDetails.open = true;
mapDetails.dispatchEvent(new window.Event("toggle"));
const images = [...mapArea.querySelectorAll("[data-map-tiles] img")];
assert(images.length > 0);
assert(images.every(image => image.referrerPolicy === "origin"), "map must send its site origin despite page-level same-origin policy");
assert(images.every(image => /^https:\/\/tile\.openstreetmap\.org\/\d+\/\d+\/\d+\.png$/.test(image.src)), "stable tile URLs preserve native HTTP caching");
update(position);
assert.deepEqual([...mapArea.querySelectorAll("[data-map-tiles] img")], images, "unchanged viewport must reuse tile elements");
map.dispatchEvent(new window.KeyboardEvent("keydown", { key: "ArrowRight", bubbles: true, cancelable: true }));
const movedImages = [...mapArea.querySelectorAll("[data-map-tiles] img")];
assert(movedImages.some(image => images.includes(image)), "panning must reuse overlapping tiles");
map.dispatchEvent(new window.KeyboardEvent("keydown", { key: "Enter", bubbles: true, cancelable: true }));
assert(Math.abs(Number(mapArea.querySelector('[name="longitude"]').value) - (position.longitude + 64 / (256 * 2 ** 5) * 360)) < 0.00001, "moving and selecting must preserve the actual longitude instead of jumping 180 degrees");
mapDetails.open = false;
update({ ...position, latitude: 40 });
assert.deepEqual([...mapArea.querySelectorAll("[data-map-tiles] img")], movedImages, "closed map must not fetch a new viewport");
update.dispose();
dom.window.close();
console.log("PASS: measured IP defaults, explicit place search, stable drafts, coordinates confirmation, origin referrer, visible-only tiles and tile reuse.");
