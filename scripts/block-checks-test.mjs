import path from "node:path";
const require = createRequire(path.join(process.env.TZA_UI_DEPS || "/tmp/tza-ui-deps", "package.json"));
const { JSDOM } = require("jsdom");
const { build } = require("esbuild");
const root = fileURLToPath(new URL("../", import.meta.url));
const bundle = await build({ stdin: { contents: 'export { blockTaskEditor, blockChecksHTML, wireBlockChecks } from "./web/block-checks.js";', resolveDir: root }, bundle: true, format: "iife", globalName: "Block", write: false });
const dom = new JSDOM('<main></main><dialog id="dialog"></dialog><div id="toast"></div>', { url: "http://127.0.0.1/admin", runScripts: "outside-only" });
const w = dom.window;
w.HTMLDialogElement.prototype.showModal = function() { this.open = true; };
w.HTMLDialogElement.prototype.close = function() { this.open = false; };
let sent, saved = false;
w.fetch = async (url, options) => { sent = { url, method: options.method, body: JSON.parse(options.body) }; return new Response('{"id":"task"}', { headers: { "Content-Type": "application/json" } }); };
