blockTaskEditor(null, [{id: "cn", name: '<img src=x onerror="alert(1)">', region: "上海", online: true}, {id: "global", name: "Overseas", region: "香港", online: true}], () => {saved = true;});
const form = w.document.querySelector("form");
assert.equal(form.querySelectorAll("img").length, 0, "escape node names");
const set = (name, value) => { form.elements.namedItem(name).value = value; };
const choose = (role, id) => { const el = [...form.querySelectorAll(`input[name="${role}"]`)].find((e) => e.value === id); el.checked = true; el.dispatchEvent(new w.Event("change", { bubbles: true })); return el; };
const cn = choose("mainland", "cn");
choose("overseas", "cn");
assert.equal(cn.checked, false, "a node cannot be both mainland and overseas");
choose("mainland", "cn");
choose("overseas", "global");
set("host", "2606:4700:4700::1111");set("family", "ipv6");set("port", "8443");set("interval", "60");
await form.onsubmit(new w.Event("submit", { cancelable: true }));
